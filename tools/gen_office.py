#!/usr/bin/env python3
"""Generate worlds/office.sdf - a small office floor (6 x 4 m) for the AlphaBot2:
central corridor, 5 rooms with doorways, an inner connecting door and furniture."""
import math
import sys

H = 0.25        # wall height
T = 0.05        # wall thickness
DOOR = 0.50     # doorway width

WALL_COL = '0.85 0.84 0.80 1'
FURN_COL = '0.55 0.40 0.25 1'
DARK_COL = '0.25 0.25 0.28 1'
PLANT_COL = '0.20 0.50 0.25 1'

links = []
segments = []   # for preview: (x0, y0, x1, y1)
furniture = []  # for preview: ('box', cx, cy, sx, sy) / ('cyl', cx, cy, r)


def box(name, cx, cy, sx, sy, sz=H, z=None, col=WALL_COL):
    z = sz / 2 if z is None else z
    links.append(f'''      <link name="{name}">
        <pose>{cx:.3f} {cy:.3f} {z:.3f} 0 0 0</pose>
        <collision name="c"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry></collision>
        <visual name="v"><geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>
          <material><ambient>{col}</ambient><diffuse>{col}</diffuse></material></visual>
      </link>''')


def cyl(name, cx, cy, r, sz=H, z=None, col=DARK_COL):
    z = sz / 2 if z is None else z
    links.append(f'''      <link name="{name}">
        <pose>{cx:.3f} {cy:.3f} {z:.3f} 0 0 0</pose>
        <collision name="c"><geometry><cylinder><radius>{r:.3f}</radius><length>{sz:.3f}</length></cylinder></geometry></collision>
        <visual name="v"><geometry><cylinder><radius>{r:.3f}</radius><length>{sz:.3f}</length></cylinder></geometry>
          <material><ambient>{col}</ambient><diffuse>{col}</diffuse></material></visual>
      </link>''')
    furniture.append(('cyl', cx, cy, r))


def wall(name, x0, y0, x1, y1, doors=()):
    """Axis-aligned wall from (x0,y0) to (x1,y1) with doorways centred at the given
    coordinates along the wall."""
    horizontal = abs(y1 - y0) < 1e-9
    a0, a1 = (min(x0, x1), max(x0, x1)) if horizontal else (min(y0, y1), max(y0, y1))
    cuts = sorted(doors)
    pieces, start = [], a0
    for d in cuts:
        pieces.append((start, d - DOOR / 2))
        start = d + DOOR / 2
    pieces.append((start, a1))
    for i, (p0, p1) in enumerate(pieces):
        if p1 - p0 < 1e-3:
            continue
        mid, length = (p0 + p1) / 2, p1 - p0
        if horizontal:
            box(f'{name}_{i}', mid, y0, length + T, T)
            segments.append((p0, y0, p1, y0))
        else:
            box(f'{name}_{i}', x0, mid, T, length + T)
            segments.append((x0, p0, x0, p1))


def furn(name, cx, cy, sx, sy, sz=H, col=FURN_COL):
    box(name, cx, cy, sx, sy, sz, col=col)
    furniture.append(('box', cx, cy, sx, sy))


# ---------------- layout ----------------
X0, X1, Y0, Y1 = -3.0, 3.0, -2.0, 2.0
CY = 0.35                       # corridor half-width -> corridor 0.70 m wide

# outer walls
wall('outer_n', X0, Y1, X1, Y1)
wall('outer_s', X0, Y0, X1, Y0)
wall('outer_w', X0, Y0, X0, Y1)
wall('outer_e', X1, Y0, X1, Y1)

# corridor walls with doors into the rooms
wall('corr_n', X0, CY, X1, CY, doors=(-2.0, 0.3, 2.2))     # doors: N1, N2, N3
wall('corr_s', X0, -CY, X1, -CY, doors=(-1.5, 1.2))        # doors: S1, S2

# north room partitions (N1 | N2 | N3), N1-N2 connected by an inner door
wall('part_n1', -1.0, CY, -1.0, Y1, doors=(1.45,))
wall('part_n2', 1.0, CY, 1.0, Y1)
# south partition (S1 | S2)
wall('part_s', 0.0, Y0, 0.0, -CY)
# S2: partial inner wall creating a dead-end alcove
wall('s2_inner', 1.8, -1.2, 3.0, -1.2)

# ---- furniture ----
# N1 (office): desk + cabinet
furn('n1_desk', -2.3, 1.55, 0.80, 0.40)
furn('n1_cabinet', -1.3, 0.80, 0.25, 0.45)
# N2 (meeting room): table on 4 legs - the robot can drive under the top,
# the lidar only sees the legs
for i, (lx, ly) in enumerate([(-0.4, 1.0), (0.4, 1.0), (-0.4, 1.5), (0.4, 1.5)]):
    cyl(f'n2_leg_{i}', lx, ly, 0.02, sz=0.30, col=DARK_COL)
box('n2_tabletop', 0.0, 1.25, 0.90, 0.60, 0.03, z=0.315, col=FURN_COL)
furniture.append(('box', 0.0, 1.25, 0.90, 0.60))
# N3 (lounge): L-shaped sofa + plant
furn('n3_sofa_a', 2.55, 1.30, 0.40, 1.00)
furn('n3_sofa_b', 2.05, 1.70, 0.60, 0.40)
cyl('n3_plant', 1.35, 0.75, 0.10, col=PLANT_COL)
# S1 (storage): shelves along walls + boxes
furn('s1_shelf_w', -2.80, -1.20, 0.30, 1.20)
furn('s1_shelf_s', -1.30, -1.80, 1.20, 0.30)
furn('s1_box_a', -1.90, -1.00, 0.30, 0.30)
furn('s1_box_b', -0.60, -1.10, 0.35, 0.25)
# S2 (lab): workbench + column
furn('s2_bench', 0.60, -1.75, 1.00, 0.40)
cyl('s2_column', 1.20, -0.90, 0.08, col=DARK_COL)
# corridor: a bin narrowing the corridor
cyl('corr_bin', -0.40, 0.18, 0.09, col=DARK_COL)

# ---------------- write SDF ----------------
sdf = f'''<?xml version="1.0"?>
<!-- Generated by gen_office.py - small office floor (6 x 4 m) for the AlphaBot2 digital twin.
     Corridor 0.70 m, doorways {DOOR:.2f} m, 5 rooms (N1 office, N2 meeting, N3 lounge, S1 storage, S2 lab).
     Robot spawn (0, 0) is in the corridor. -->
<sdf version="1.9">
  <world name="alphabot2_office">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="c"><geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry></collision>
        <visual name="v"><geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
          <material><ambient>0.5 0.5 0.5 1</ambient><diffuse>0.6 0.6 0.6 1</diffuse></material></visual>
      </link>
    </model>

    <model name="office">
      <static>true</static>
{chr(10).join(links)}
    </model>
  </world>
</sdf>
'''
out = sys.argv[1] if len(sys.argv) > 1 else 'office.sdf'
open(out, 'w').write(sdf)

# ---------------- preview ----------------
if len(sys.argv) > 2:
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.patches import Rectangle, Circle
    wps = [(-2.0, 1.0, 'A'), (-0.6, 1.75, 'B'), (2.0, 0.9, 'C'),
           (2.4, -0.8, 'D'), (2.6, -1.6, 'E'), (-2.2, -0.6, 'F'), (0.0, 0.0, 'home')]
    fig, ax = plt.subplots(figsize=(9, 6.3))
    for x0, y0, x1, y1 in segments:
        ax.plot([x0, x1], [y0, y1], color='#444', lw=3, solid_capstyle='butt')
    for f in furniture:
        if f[0] == 'box':
            _, cx, cy, sx, sy = f
            ax.add_patch(Rectangle((cx - sx / 2, cy - sy / 2), sx, sy, color='#b08a5a', alpha=0.8))
        else:
            _, cx, cy, r = f
            ax.add_patch(Circle((cx, cy), r, color='#3a5', alpha=0.9))
    for x, y, n in wps:
        ax.plot(x, y, 'o', color='#d33', ms=8)
        ax.annotate(n, (x, y), textcoords='offset points', xytext=(6, 6), color='#d33', fontsize=11, weight='bold')
    for x, y, n in [(-2.0, 1.2, 'N1 office'), (0.0, 0.6, 'N2 meeting'), (1.6, 1.3, 'N3 lounge'),
                    (-1.6, -0.6, 'S1 storage'), (1.0, -0.6, 'S2 lab'), (-2.6, 0.0, 'corridor')]:
        ax.text(x, y, n, fontsize=9, color='#226', ha='center')
    ax.add_patch(Circle((0, 0), 0.065, color='#25c'))
    ax.set_aspect('equal'); ax.set_xlim(-3.3, 3.3); ax.set_ylim(-2.3, 2.3)
    ax.grid(alpha=0.3); ax.set_xlabel('x [m]'); ax.set_ylabel('y [m]')
    ax.set_title('office.sdf - top view (red = patrol waypoints)')
    fig.tight_layout(); fig.savefig(sys.argv[2], dpi=110)
